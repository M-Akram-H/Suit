//! Translation of Manim Core to Python for manim-slides (docs/spec/manim-core.md §7).
//!
//! Compositional: one Manim call per node. The input must have been checked; facts the
//! checker established (run times, live waits, layers) are read from its notes.

pub mod formula;
pub mod pretty;
mod python;

use std::{cell::Cell, fmt::Write};

use suit_check::{Checked, Note};
use suit_core::{
    Anim, Arg, Args, Blueprint, Call, Command, Deck, Direction, Expr, Node, Object, Opts, Place,
    Slide, SlideContent, Sym, Updater, VarId,
};
use suit_sig::{Pass, PyForm, Signature};

use crate::python::{float, identifier, string};

#[derive(Clone, Debug)]
pub struct Options {
    /// Name of the generated scene class.
    pub class_name: String,
    /// Render at this pixel height instead of the deck's, keeping its aspect ratio. Timing
    /// is unaffected, so this is safe for previews.
    pub pixel_height: Option<u32>,
}

impl Default for Options {
    fn default() -> Self {
        Options {
            class_name: "Deck".to_owned(),
            pixel_height: None,
        }
    }
}

/// Manim's frame height in scene units; the width follows from the aspect ratio.
const FRAME_HEIGHT: f64 = 8.0;

const RELAYER: &str = r#"
def _relayer(mobject, base):
    """Give a copied group layers of its own, keeping its members' order."""
    levels = sorted({m.z_index for m in mobject.get_family()})
    for m in mobject.get_family():
        m.set_z_index(base + levels.index(m.z_index) / (len(levels) + 1), family=False)
    return mobject

"#;

pub fn export(deck: &Deck, sig: &Signature, checked: &Checked, options: &Options) -> String {
    let exporter = Exporter {
        deck,
        sig,
        checked,
        mode: Mode::Slides,
        frame_time: Cell::new(None),
    };
    let mut out = String::new();
    exporter.header(&mut out, options);
    for (index, slide) in deck.slides.iter().enumerate() {
        exporter.slide(&mut out, slide, index);
    }
    out
}

/// The runtime half of the probes; see [`probe`] and [`probe_frames`].
const PROBE: &str = include_str!("probe.py");

/// What the catalogue has that Manim has not: `Plot`. Written into every file that uses it.
const PLOT: &str = include_str!("plot.py");

/// And `Tangent`, with `Glide`. A tangent is to a `Plot`, so that is there whenever this is.
const TANGENT: &str = include_str!("tangent.py");

/// What a generated script is for.
#[derive(Clone, Copy, PartialEq)]
enum Mode {
    /// The deck itself, for manim-slides.
    Slides,
    /// The deck slide by slide, for the probes: each slide's steps as a piece of its own,
    /// with a call into the probe after every one.
    Probe,
}

/// A Python script that runs the deck without rendering it and writes, as JSON to the path
/// given as its first argument, the outline of everything on scene after every step. This
/// is how the editor's canvas shows exactly what Manim would draw.
///
/// Animations are skipped to their end state, so time-based updaters see one long frame
/// per step instead of many short ones.
pub fn probe(deck: &Deck, sig: &Signature, checked: &Checked) -> String {
    probe_slides(deck, sig, checked, 0, deck.slides.len().saturating_sub(1))
}

/// The same for some of the slides only: those from number `have`, which the caller has no
/// use reporting before, to number `last`. Run by a Manim that has run the slides before
/// them already and kept what they left behind, it does not run them again.
pub fn probe_slides(
    deck: &Deck,
    sig: &Signature,
    checked: &Checked,
    have: usize,
    last: usize,
) -> String {
    let run = format!("_run(_SLIDES, \"steps\", {have}, {last}, sys.argv[1])");
    probe_script(deck, sig, checked, last, &run)
}

/// A Python script that plays slide `slide` in Manim, frame for frame as a render would,
/// and writes what is drawn in each frame instead of drawing it. The editor plays the
/// result back on its canvas: the real animation, without a video in between.
///
/// A still `wait` is recorded as one frame repeated rather than waited through, because the
/// recording itself would make Manim treat the scene as live (spec §6.5).
pub fn probe_frames(deck: &Deck, sig: &Signature, checked: &Checked, slide: usize) -> String {
    let run = format!("_run(_SLIDES, \"frames\", {slide}, {slide}, sys.argv[1])");
    probe_script(deck, sig, checked, slide, &run)
}

/// The slides up to `last`, each as a piece of Python, and `run` to say what to do with them.
fn probe_script(deck: &Deck, sig: &Signature, checked: &Checked, last: usize, run: &str) -> String {
    let exporter = Exporter {
        deck,
        sig,
        checked,
        mode: Mode::Probe,
        frame_time: Cell::new(None),
    };
    let config = &deck.config;
    let frame_width = FRAME_HEIGHT * f64::from(config.width) / f64::from(config.height);
    let mut out = String::new();
    out.push_str("\"\"\"Generated by Suit: reports what Manim would draw.\"\"\"\n\n");
    out.push_str("import json\nimport sys\n\nimport numpy as np\nfrom manim import *\n");
    out.push_str("from manim.utils import rate_functions\n\n");
    let _ = writeln!(out, "config.frame_rate = {}", config.fps);
    let _ = writeln!(out, "config.frame_height = {}", float(FRAME_HEIGHT));
    let _ = writeln!(out, "config.frame_width = {}", float(frame_width));
    out.push_str("config.dry_run = True\nconfig.verbosity = \"ERROR\"\n");
    out.push_str("config.progress_bar = \"none\"\n\n\n");
    out.push_str(PROBE);
    // What the slides may call that is not Manim's. A probe's scene outlives the script
    // that made it, so every script defines all of it, used or not.
    out.push_str("\n\n");
    out.push_str(PLOT);
    out.push_str("\n\n");
    out.push_str(TANGENT);
    out.push_str(RELAYER);
    // Each slide is a text of its own, so that it can be run by itself, starting from
    // what the slides before it left behind.
    out.push_str("\n\n_SLIDES = [\n");
    for (index, slide) in deck.slides.iter().enumerate().take(last + 1) {
        let mut body = String::new();
        exporter.slide(&mut body, slide, index);
        let _ = writeln!(out, "    (  # slide {}", index + 1);
        for line in body.lines().filter(|line| !line.trim().is_empty()) {
            let line = line.strip_prefix(INDENT).unwrap_or(line);
            let _ = writeln!(out, "        {}", string(&format!("{line}\n")));
        }
        out.push_str("        \"\"\n    ),\n");
    }
    out.push_str("]\n\n");
    let _ = writeln!(out, "{run}");
    out
}

struct Exporter<'a> {
    deck: &'a Deck,
    sig: &'a Signature,
    checked: &'a Checked,
    mode: Mode,
    /// While an updater that is given the frame time is written: the variable that stands
    /// for it. Manim passes the time only to a parameter called `dt`, so that is its name.
    frame_time: Cell<Option<VarId>>,
}

/// Statements inside `construct`.
const INDENT: &str = "        ";

impl Exporter<'_> {
    fn header(&self, out: &mut String, options: &Options) {
        let config = &self.deck.config;
        let height = options.pixel_height.unwrap_or(config.height);
        // Round the width to an even number of pixels, as video encoders require.
        let exact_width = f64::from(height) * f64::from(config.width) / f64::from(config.height);
        let width = ((exact_width / 2.0).round() as u32) * 2;
        let frame_width = FRAME_HEIGHT * f64::from(config.width) / f64::from(config.height);

        out.push_str(
            "\"\"\"Generated by Suit. Edits are overwritten on the next export.\"\"\"\n\n",
        );
        if self.names_pictures_from_its_folder() {
            out.push_str("from pathlib import Path\n\n");
        }
        out.push_str("import numpy as np\nfrom manim import *\n");
        out.push_str("from manim.utils import rate_functions\nfrom manim_slides import Slide\n\n");
        let _ = writeln!(out, "config.pixel_width = {width}");
        let _ = writeln!(out, "config.pixel_height = {height}");
        let _ = writeln!(out, "config.frame_rate = {}", config.fps);
        let _ = writeln!(out, "config.frame_height = {}", float(FRAME_HEIGHT));
        let _ = writeln!(out, "config.frame_width = {}", float(frame_width));
        let _ = writeln!(
            out,
            "config.background_color = {}",
            string(&config.background.hex_rgb())
        );
        if self.names_pictures_from_its_folder() {
            // Wherever Manim is started from, they are found next to this file.
            out.push_str("config.assets_dir = str(Path(__file__).resolve().parent)\n");
        }
        out.push('\n');
        if self.checked.notes.values().any(|note| note.copies_group) {
            out.push_str(RELAYER);
        }
        if self.makes("Plot") {
            out.push('\n');
            out.push_str(PLOT);
            out.push('\n');
        }
        if self.makes("Tangent") {
            out.push('\n');
            out.push_str(TANGENT);
            out.push('\n');
        }
        let _ = writeln!(out, "\nclass {}(Slide):", options.class_name);
        out.push_str("    def construct(self):\n");
    }

    /// Whether the deck makes an object with the constructor `wanted` anywhere.
    fn makes(&self, wanted: &str) -> bool {
        fn made(object: &Object, wanted: &str) -> bool {
            match object {
                Object::New { ctor, args } => &**ctor == wanted
                    || args.iter().any(
                        |(_, arg)| matches!(arg, Arg::Object(inner) if made(&inner.item, wanted)),
                    ),
                Object::Chain { base, .. } => made(&base.item, wanted),
                Object::Group { .. } | Object::Copy(_) => false,
            }
        }
        let blueprints = self
            .deck
            .slides
            .iter()
            .filter_map(|slide| match &slide.content {
                SlideContent::Blueprint(blueprint) => Some(blueprint),
                SlideContent::Media { .. } => None,
            });
        blueprints.flat_map(|blueprint| &blueprint.body).any(
            |node| matches!(&node.item, Command::LetObject { value, .. } if made(&value.item, wanted)),
        )
    }

    /// Whether some picture of the deck is named relative to where the deck is.
    fn names_pictures_from_its_folder(&self) -> bool {
        fn relative(object: &Object) -> bool {
            match object {
                Object::New { ctor, args } => {
                    &**ctor == "ImageMobject"
                        && args.iter().any(|(_, arg)| {
                            matches!(arg, Arg::Expr(Expr::Str(file)) if !file.starts_with('/'))
                        })
                }
                Object::Chain { base, .. } => relative(&base.item),
                Object::Group { .. } | Object::Copy(_) => false,
            }
        }
        let blueprints = self
            .deck
            .slides
            .iter()
            .filter_map(|slide| match &slide.content {
                SlideContent::Blueprint(blueprint) => Some(blueprint),
                SlideContent::Media { .. } => None,
            });
        blueprints.flat_map(|blueprint| &blueprint.body).any(
            |node| matches!(&node.item, Command::LetObject { value, .. } if relative(&value.item)),
        )
    }

    fn slide(&self, out: &mut String, slide: &Slide, index: usize) {
        // A probe is told nothing that does not change what Manim draws, the title least
        // of all: it tells what it has run before by the text of the slides.
        if self.mode == Mode::Slides {
            let title = slide.title.replace(['\n', '\r'], " ");
            let _ = writeln!(out, "{INDENT}# ── Slide {}: {title} ──", index + 1);
        }

        let config = &slide.config;
        let mut settings = Vec::new();
        if let SlideContent::Media { path } = &slide.content {
            settings.push(format!("src={}", string(path)));
        }
        if config.looping {
            settings.push("loop=True".to_owned());
        }
        if config.auto_next {
            settings.push("auto_next=True".to_owned());
        }
        if config.skip {
            settings.push("skip_animations=True".to_owned());
        }
        if config.playback_rate != 1.0 {
            settings.push(format!("playback_rate={}", float(config.playback_rate)));
        }
        if config.reversed_playback_rate != 1.0 {
            settings.push(format!(
                "reversed_playback_rate={}",
                float(config.reversed_playback_rate)
            ));
        }
        if !config.notes.is_empty() {
            settings.push(format!("notes={}", string(&config.notes)));
        }
        if config.direction == Direction::Vertical {
            settings.push("direction=\"vertical\"".to_owned());
        }
        match self.mode {
            Mode::Probe => {
                let _ = writeln!(out, "{INDENT}_probe.enter({index})");
            }
            // The first slide starts by itself; a call is only needed to configure it.
            Mode::Slides if index > 0 || !settings.is_empty() => {
                let _ = writeln!(out, "{INDENT}self.next_slide({})", settings.join(", "));
            }
            Mode::Slides => {}
        }

        if let SlideContent::Blueprint(blueprint) = &slide.content {
            self.blueprint(out, blueprint);
            // The hold that lets the slide rest on its finished state (spec §6.6). Emitted
            // here rather than left to manim-slides so that it obeys the same still-or-live
            // rule as every other wait.
            let report = &self.checked.slides[index];
            if report.gap_frames > 0 {
                let secs = self.deck.config.gap.secs();
                self.wait(out, secs, report.gap_live, report.gap_frames);
            }
        }
        out.push('\n');
    }

    fn blueprint(&self, out: &mut String, blueprint: &Blueprint) {
        for node in &blueprint.body {
            let note = self
                .checked
                .notes
                .get(&node.id)
                .cloned()
                .unwrap_or_default();
            self.command(out, &node.item, &note);
            if self.mode == Mode::Probe {
                if let Command::LetObject { var, .. } = &node.item {
                    let _ = writeln!(out, "{INDENT}_probe.name({}, {})", var.0, self.var(*var));
                }
                let _ = writeln!(out, "{INDENT}_probe.after({})", node.id.0);
            }
        }
    }

    fn command(&self, out: &mut String, command: &Command, note: &Note) {
        match command {
            Command::LetObject { var, value } => {
                let name = self.var(*var);
                let object = self.object(value);
                match (note.layer, note.copies_group) {
                    (Some(layer), true) => {
                        let _ = writeln!(out, "{INDENT}{name} = _relayer({object}, {layer})");
                    }
                    (layer, _) => {
                        let _ = writeln!(out, "{INDENT}{name} = {object}");
                        if let Some(layer) = layer {
                            let _ = writeln!(out, "{INDENT}{name}.set_z_index({layer})");
                        }
                    }
                }
                // Listing the group itself is what makes its own updaters run (spec §6.3).
                if note.group_on_scene {
                    let _ = writeln!(out, "{INDENT}self.add({name})");
                }
            }
            Command::LetValue { var, value } => {
                let _ = writeln!(out, "{INDENT}{} = {}", self.var(*var), self.expr(value));
            }
            Command::Apply { target, call } => {
                let _ = writeln!(out, "{INDENT}{}", self.call(&self.place(target), call));
            }
            Command::Add { targets } => {
                let _ = writeln!(out, "{INDENT}self.add({})", self.places(targets));
            }
            Command::Remove { targets } => {
                let _ = writeln!(out, "{INDENT}self.remove({})", self.places(targets));
            }
            Command::Play { anims } => {
                let anims: Vec<String> = anims.iter().map(|anim| self.anim(anim)).collect();
                match anims.as_slice() {
                    [only] => {
                        let _ = writeln!(out, "{INDENT}self.play({only})");
                    }
                    several => {
                        let _ = writeln!(out, "{INDENT}self.play(");
                        for anim in several {
                            let _ = writeln!(out, "{INDENT}    {anim},");
                        }
                        let _ = writeln!(out, "{INDENT})");
                    }
                }
            }
            Command::Wait { duration } => {
                self.wait(out, duration.secs(), note.live, note.frames);
            }
            Command::Attach { target, updater } => {
                let (params, call) = match updater {
                    Updater::Always(call) => ("m", call),
                    Updater::Every { dt, call } => {
                        self.frame_time.set(Some(*dt));
                        ("m, dt", call)
                    }
                };
                let body = self.call("m", call);
                self.frame_time.set(None);
                let _ = writeln!(
                    out,
                    "{INDENT}{}.add_updater(lambda {params}: {body})",
                    self.place(target)
                );
            }
            Command::Detach { target } => {
                let _ = writeln!(out, "{INDENT}{}.clear_updaters()", self.place(target));
            }
            Command::Raw(raw) => {
                for line in raw.python.lines() {
                    let _ = writeln!(out, "{INDENT}{line}");
                }
            }
        }
    }

    /// A wait on a scene with running updaters must not be frozen, or the first frame
    /// shows them stale (spec §6.5, Q4). `frames` is how long it lasts (spec §5.7).
    fn wait(&self, out: &mut String, secs: f64, live: bool, frames: u32) {
        match (self.mode, live) {
            // The probe decides: while it records, Manim treats every wait as live, so a
            // still one is written down as its one frame, repeated, instead of waited
            // through.
            (Mode::Probe, _) => {
                let live = if live { "True" } else { "False" };
                let _ = writeln!(
                    out,
                    "{INDENT}_probe.wait({}, {frames}, {live})",
                    float(secs)
                );
            }
            (Mode::Slides, true) => {
                let _ = writeln!(
                    out,
                    "{INDENT}self.wait({}, frozen_frame=False)",
                    float(secs)
                );
            }
            (Mode::Slides, false) => {
                let _ = writeln!(out, "{INDENT}self.wait({})", float(secs));
            }
        }
    }

    // ── Animations ───────────────────────────────────────────────────────────

    fn anim(&self, node: &Node<Anim>) -> String {
        let run_time = self
            .checked
            .notes
            .get(&node.id)
            .and_then(|note| note.run_time);
        match &node.item {
            Anim::Prim { ctor, args, opts } => {
                let mut parts = match self.sig.anims.get(ctor) {
                    Some(anim) => {
                        let params = anim.params.iter().map(|p| (&p.name, p.pass));
                        self.args(params, args)
                    }
                    None => Vec::new(),
                };
                // Always explicit: several animations derive their default length from the
                // object, which would make the timeline depend on a render.
                parts.extend(self.opts(opts, run_time));
                format!("{ctor}({})", parts.join(", "))
            }
            Anim::Animate {
                target,
                calls,
                opts,
            } => {
                let builder = format!(
                    "{}.animate({})",
                    self.place(target),
                    self.opts(opts, run_time).join(", ")
                );
                calls
                    .iter()
                    .fold(builder, |receiver, call| self.call(&receiver, call))
            }
            Anim::Par { items, opts } | Anim::Seq { items, opts } => {
                let class = match node.item {
                    Anim::Seq { .. } => "Succession",
                    _ => "AnimationGroup",
                };
                let mut parts: Vec<String> = items.iter().map(|item| self.anim(item)).collect();
                // A composite's own length follows from its children unless it was set.
                parts.extend(self.opts(opts, opts.run_time.map(|time| time.secs())));
                format!("{class}({})", parts.join(", "))
            }
        }
    }

    fn opts(&self, opts: &Opts, run_time: Option<f64>) -> Vec<String> {
        let mut parts = Vec::new();
        if let Some(run_time) = run_time {
            parts.push(format!("run_time={}", float(run_time)));
        }
        if let Some(rate) = &opts.rate {
            parts.push(format!("rate_func={}", self.rate(rate)));
        }
        if let Some(lag) = opts.lag {
            parts.push(format!("lag_ratio={}", float(lag)));
        }
        parts
    }

    fn rate(&self, rate: &Sym) -> String {
        self.sig
            .rates
            .get(rate)
            .cloned()
            .unwrap_or_else(|| rate.to_string())
    }

    // ── Objects ──────────────────────────────────────────────────────────────

    fn object(&self, node: &Node<Object>) -> String {
        match &node.item {
            Object::New { ctor, args } => {
                let parts = match self.sig.ctors.get(ctor) {
                    Some(sig) => {
                        let params = self.sig.ctor_params(sig);
                        self.args(params.iter().map(|p| (&p.name, p.pass)), args)
                    }
                    None => Vec::new(),
                };
                format!("{ctor}({})", parts.join(", "))
            }
            Object::Group { vector, items } => {
                let class = if *vector { "VGroup" } else { "Group" };
                format!("{class}({})", self.places(items))
            }
            Object::Copy(source) => format!("{}.copy()", self.place(source)),
            Object::Chain { base, call } => self.call(&self.object(base), call),
        }
    }

    /// `receiver.method(args)`. The method is looked up by name only: the checker already
    /// chose the overload, and overloads share their parameter names' passing style.
    fn call(&self, receiver: &str, call: &Call) -> String {
        let parts = match self.sig.methods.get(&call.method) {
            Some(overloads) => {
                let overload = overloads
                    .iter()
                    .find(|m| {
                        call.args
                            .iter()
                            .all(|(name, _)| m.params.iter().any(|p| p.name == *name))
                    })
                    .unwrap_or(&overloads[0]);
                self.args(
                    overload.params.iter().map(|p| (&p.name, p.pass)),
                    &call.args,
                )
            }
            None => Vec::new(),
        };
        format!("{receiver}.{}({})", call.method, parts.join(", "))
    }

    /// Arguments in the order and style Python needs (see [`Pass`]).
    fn args<'p>(&self, params: impl Iterator<Item = (&'p Sym, Pass)>, args: &Args) -> Vec<String> {
        let mut positional = Vec::new();
        let mut keyword = Vec::new();
        let mut gap = false;
        for (name, pass) in params {
            let mut given = args
                .iter()
                .filter(|(arg, _)| arg == name)
                .map(|(_, arg)| self.arg(arg));
            match pass {
                Pass::Variadic => positional.extend(given),
                Pass::List => {
                    let items: Vec<String> = given.collect();
                    if !items.is_empty() {
                        keyword.push(format!("{name}=[{}]", items.join(", ")));
                    }
                }
                Pass::Positional if !gap => match given.next() {
                    Some(value) => positional.push(value),
                    None => gap = true,
                },
                Pass::Positional | Pass::Keyword => {
                    keyword.extend(given.next().map(|value| format!("{name}={value}")))
                }
            }
        }
        positional.extend(keyword);
        positional
    }

    fn arg(&self, arg: &Arg) -> String {
        match arg {
            Arg::Expr(expr) => self.expr(expr),
            Arg::Object(object) => self.object(object),
            Arg::Fun { param, body } => format!("lambda {}: {}", self.var(*param), self.expr(body)),
            Arg::Rate(rate) => self.rate(rate),
        }
    }

    // ── Expressions ──────────────────────────────────────────────────────────

    fn expr(&self, expr: &Expr) -> String {
        match expr {
            Expr::Real(value) => float(*value),
            Expr::Int(value) => value.to_string(),
            Expr::Bool(true) => "True".to_owned(),
            Expr::Bool(false) => "False".to_owned(),
            Expr::Str(value) => string(value),
            Expr::Vec3(parts) => {
                // An array of whole numbers refuses real arithmetic in place, and nothing
                // says Manim never does that to a point it is given. So whole numbers are
                // written as the reals they stand for, and anything computed is made real
                // by the array itself.
                let part = |part: &Expr| match part {
                    Expr::Int(whole) => float(*whole as f64),
                    other => self.expr(other),
                };
                let written = parts.each_ref().map(part).join(", ");
                let plain = |part: &Expr| matches!(part, Expr::Real(_) | Expr::Int(_));
                match parts.iter().all(plain) {
                    true => format!("np.array([{written}])"),
                    false => format!("np.array([{written}], dtype=float)"),
                }
            }
            Expr::Color(color) => format!("ManimColor({})", string(&color.hex())),
            Expr::Const(name) => name.to_string(),
            Expr::Var(var) => self.var(*var),
            Expr::Place(place) => self.place(place),
            Expr::Call { fun, args } => {
                let args: Vec<String> = args.iter().map(|arg| self.expr(arg)).collect();
                // Any overload will do: overloads of one name share their spelling.
                let form = self
                    .sig
                    .fns
                    .get(fun)
                    .and_then(|overloads| overloads.first())
                    .map(|f| &f.py);
                match (form, args.as_slice()) {
                    (Some(PyForm::Infix(op)), [left, right]) => format!("({left} {op} {right})"),
                    (Some(PyForm::Prefix(op)), [operand]) => format!("({op}{operand})"),
                    (Some(PyForm::Index(index)), [vector]) => format!("{vector}[{index}]"),
                    (Some(PyForm::Call(function)), _) => format!("{function}({})", args.join(", ")),
                    _ => format!("{fun}({})", args.join(", ")),
                }
            }
            Expr::If {
                cond,
                then,
                otherwise,
            } => {
                format!(
                    "({} if {} else {})",
                    self.expr(then),
                    self.expr(cond),
                    self.expr(otherwise)
                )
            }
            Expr::Query {
                target,
                query,
                args,
            } => {
                let place = self.place(target);
                // Resolved by name; the overloads of a query agree on being a property.
                match self
                    .sig
                    .queries
                    .get(query)
                    .and_then(|overloads| overloads.first())
                {
                    Some(sig) if sig.property => format!("{place}.{query}"),
                    Some(sig) => {
                        let parts = self.args(sig.params.iter().map(|p| (&p.name, p.pass)), args);
                        format!("{place}.{query}({})", parts.join(", "))
                    }
                    None => format!("{place}.{query}()"),
                }
            }
        }
    }

    fn places(&self, places: &[Place]) -> String {
        places
            .iter()
            .map(|place| self.place(place))
            .collect::<Vec<_>>()
            .join(", ")
    }

    fn place(&self, place: &Place) -> String {
        let path: String = place
            .path
            .iter()
            .map(|index| format!("[{index}]"))
            .collect();
        format!("{}{path}", self.var(place.root))
    }

    /// The Python name of a variable: its display name made an identifier, plus its id, so
    /// that it is unique and cannot shadow anything Manim exports.
    fn var(&self, var: VarId) -> String {
        if self.frame_time.get() == Some(var) {
            return "dt".to_owned();
        }
        let name = self.deck.names.get(&var).map_or("", String::as_str);
        format!("{}_{}", identifier(name), var.0)
    }
}
