"""Regenerate crates/sig/src/colors.rs from the installed Manim's colour constants."""
import pathlib

import manim

names = sorted(n for n in dir(manim) if n.isupper() and isinstance(getattr(manim, n), manim.ManimColor))
rows = "\n".join(f'    ("{n}", "{getattr(manim, n).to_hex().lower()}"),' for n in names)
out = pathlib.Path(__file__).resolve().parent.parent / "crates/sig/src/colors.rs"
out.write_text(
    f"//! Generated by tools/gen_colors.py from manim {manim.__version__}. Do not edit.\n\n"
    f"pub(crate) const COLORS: &[(&str, &str)] = &[\n{rows}\n];\n"
)
print(f"wrote {len(names)} colours to {out}")
